BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON SCHEMA ims FROM anon';
    EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA ims FROM anon';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE 'REVOKE ALL ON SCHEMA ims FROM authenticated';
    EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA ims FROM authenticated';
  END IF;
END $$;

