#!/usr/bin/env node
/**
 * Generates src/environments/supabase.env.ts (git-ignored) from `.env` or real environment
 * variables, so Supabase settings never live in committed source files.
 *
 * Runs automatically before `npm start`, `npm run build`, `npm test` and after `npm install`.
 *
 *   SUPABASE_URL=https://<project-ref>.supabase.co
 *   SUPABASE_PUBLISHABLE_KEY=sb_publishable_...   (or the legacy anon key)
 *
 * In CI / hosting, set these as environment variables instead of a .env file.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const OUT = 'src/environments/supabase.env.ts';

if (existsSync('.env')) {
  process.loadEnvFile('.env');
}

const url = (process.env.SUPABASE_URL ?? '').trim().replace(/\/+$/, '');
const key = (process.env.SUPABASE_PUBLISHABLE_KEY ?? process.env.SUPABASE_ANON_KEY ?? '').trim();

// Refuse secret keys: they bypass row-level security and must never reach a browser.
const jwtPayload = key.split('.')[1];
const isLegacyServiceRole =
  !!jwtPayload && Buffer.from(jwtPayload, 'base64url').toString().includes('"service_role"');
if (key.startsWith('sb_secret_') || isLegacyServiceRole) {
  console.error('\n✘ SUPABASE_PUBLISHABLE_KEY is a SECRET key. Use the publishable (anon) key instead.\n');
  process.exit(1);
}
if (url && !/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)$|^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(url)) {
  console.warn(`! SUPABASE_URL looks unusual: ${url}`);
}

const content = `// AUTO-GENERATED by scripts/set-env.mjs from .env – do not edit, do not commit.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_PUBLISHABLE_KEY = ${JSON.stringify(key)};
`;

const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (previous !== content) {
  writeFileSync(OUT, content);
}
console.log(
  url && key
    ? `✔ Supabase config generated for ${url}`
    : '! SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY not set – the app will run in demo mode (sample data).',
);
